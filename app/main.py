# 行数の計算（フレームの高さ合わせ）
try:
    FRAME_HEIGHT = 13
except IndexError:
    FRAME_HEIGHT = 0

def move_cursor_up(n):
    if n <= 0: return ""
    return f"\033[{n}A"

async def ascii_generator():
    is_first_frame = True
    for frame in FRAMES:
        output = ""
        if not is_first_frame:
            output += move_cursor_up(FRAME_HEIGHT)
        
        output += frame + "\n"
        
        yield output.encode("utf-8")
        is_first_frame = False
        
        await asyncio.sleep(0.1)
    while True:
        for frame in flash:
            output = ""
            if not is_first_frame:
                output += move_cursor_up(FRAME_HEIGHT)
            
            output += frame + "\n"
            
            yield output.encode("utf-8")
            is_first_frame = False
            
            await asyncio.sleep(0.15)

@app.get("/")
async def index():
    headers = {"X-Content-Type-Options": "nosniff"}
    return StreamingResponse(
        ascii_generator(), 
        media_type="text/plain", 
        headers=headers
    )
